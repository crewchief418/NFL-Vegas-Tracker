import { NextResponse } from "next/server";
import { query } from "../../../lib/db";
import { buildPredictionReport } from "../../../lib/predictions";
import { simulateGame, DEFAULT_SIMULATIONS } from "../../../lib/simulation";

export const runtime="nodejs";
export const dynamic="force-dynamic";
export const maxDuration=60;

export async function GET(request){
  try{
    const [gamesResult,savedResult]=await Promise.all([
      query(`SELECT competition_type,source_game_id,season,to_char(game_date,'YYYY-MM-DD') AS game_date,
        to_char(game_time,'HH24:MI') AS game_time,away_team,home_team,
        COALESCE(closing_spread_points,spread_points) AS spread_points,
        COALESCE(closing_over_under_line,over_under_line) AS over_under_line,
        away_score,home_score,ats_result FROM public.games ORDER BY game_date,game_time NULLS LAST,source_game_id`),
      query(`SELECT report,generated_at FROM public.market_prediction_runs ORDER BY generated_at DESC,id DESC LIMIT 1`)
    ]);
    if(!savedResult.rows.length) return NextResponse.json({error:"Generate a forecast first so simulations use the current model predictions."},{status:409});
    const games=gamesResult.rows;
    const history=games.filter(g=>g.away_score!=null&&g.home_score!=null);
    const historicalReport=buildPredictionReport(history,[],{includeSimulationValidation:true});
    const calibration=historicalReport.simulationCalibration||[];
    const report=savedResult.rows[0].report;
    const active=new Map(games.filter(g=>g.away_score==null&&g.home_score==null).map(g=>[`${g.competition_type}:${g.source_game_id}`,g]));
    const forecasts=(report.upcoming||[]).filter(p=>active.has(`${p.competition_type}:${p.source_game_id}`));
    const simulations=forecasts.map(forecast=>{
      const game=active.get(`${forecast.competition_type}:${forecast.source_game_id}`);
      // Context adjustments are excluded from the simulation mean until they have
      // their own historical walk-forward validation. The residuals below were
      // generated by the historical baseline model without future context leakage.
      const features=forecast.feature_snapshot||{};
      const experimentalMarginAdjustment=Number(features.team_efficiency_adjustment||0)+Number(features.quarterback_performance_adjustment||0)+Number(features.quarterback_injury_adjustment||0);
      const weatherAdjustment=Number(features.weather?.total_adjustment||0);
      const baseline={...forecast,
        predicted_home_margin:Number(forecast.predicted_home_margin)-experimentalMarginAdjustment,
        predicted_total_points:Number(forecast.predicted_total_points)-weatherAdjustment};
      return {...forecast,...simulateGame(baseline,calibration,DEFAULT_SIMULATIONS),away_team:game.away_team,home_team:game.home_team,game_date:String(game.game_date).slice(0,10),game_time:game.game_time,spread_points:game.spread_points,over_under_line:game.over_under_line,
        simulationBaseline:"historical-core-model",excludedExperimentalContext:true};
    });
    return NextResponse.json({generatedAt:savedResult.rows[0].generated_at,modelVersion:report.modelVersion,calibrationGames:calibration.length,minimumCalibrationGames:100,validation:historicalReport.simulationValidation,simulations});
  }catch(error){console.error("GET /api/simulations:",error);return NextResponse.json({error:"Unable to build simulations from the historical model data."},{status:500});}
}
